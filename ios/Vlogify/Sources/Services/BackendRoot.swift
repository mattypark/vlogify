import Foundation
import VlogifyContract

/// Picks the backend. `VLOGIFY_API_URL` in Info.plist (from Base.xcconfig) is the
/// switch; blank is the mock, and the mock is a working app. UI tests and `-vlogifyDemo`
/// always get the mock, whatever the build points at, so screenshots and the walker
/// never touch a live server.
@MainActor
enum BackendRoot {
    static var config: BackendConfig? {
        let info = Bundle.main.infoDictionary ?? [:]
        return BackendConfig(apiBaseURL: info["VLOGIFY_API_URL"] as? String)
    }

    /// True when this launch runs on the on-device mock.
    static var usesMock: Bool {
        config == nil || LaunchArguments.isUITesting || LaunchArguments.demo != nil
    }

    static func make(cache: LocalMediaCache, clock: Clock) async -> Backend {
        if !usesMock, let config {
            // Backend lane: `return CloudflareBackend(config: config, tokens: KeychainTokenStore()).backend`
            _ = config
        }
        let scenarioDir = LaunchArguments.usesTemporaryStore
            ? FileManager.default.temporaryDirectory.appendingPathComponent("vlogify-mock-\(ProcessInfo.processInfo.processIdentifier)")
            : cache.root.appendingPathComponent("mock", isDirectory: true)
        // With -vlogifyHour the whole app pretends it is that hour; the mock has to
        // seed against the same instant or "today" has clips only up to real time.
        let frozen = LaunchArguments.hour == nil ? nil : clock.now
        let mock = MockBackend(now: { frozen ?? Date() }, timeZone: clock.timeZone,
                               clipsDirectory: scenarioDir, sampleClip: SampleClip.url)
        if let scenario = LaunchArguments.demo {
            await mock.seed(scenario)
        } else if let restored = MockSessionStore.load() {
            // The mock forgets everything between launches. Persisting the seed
            // choice is enough to make "I signed in yesterday" survive a relaunch,
            // which is the only part of it a person notices.
            await mock.seed(restored)
        }
        return mock.backend
    }
}

/// Remembers which seeded world the mock is in across launches.
enum MockSessionStore {
    private static let key = "mock-scenario"

    static func load() -> MockBackend.Scenario? {
        guard let data = Keychain.get(key), let raw = String(data: data, encoding: .utf8) else { return nil }
        return MockBackend.Scenario(rawValue: raw)
    }

    static func save(_ scenario: MockBackend.Scenario?) {
        guard let scenario else { Keychain.remove(key); return }
        Keychain.set(Data(scenario.rawValue.utf8), for: key)
    }
}

/// A two-second bundled clip the simulator (which has no camera) records "with", and
/// that seeded clips play back. Generated by scripts/make-sample-clip.sh.
enum SampleClip {
    static var url: URL? {
        Bundle.main.url(forResource: "sample-clip", withExtension: "mov")
    }
}
